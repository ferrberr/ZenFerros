#!/usr/bin/env python3
"""Build a Zen x86_64 kernel and its Multiboot ELF32 loader container."""
import argparse
import json
import os
from pathlib import Path
import struct
import subprocess
import time
from build_user import build_user

ROOT=Path(__file__).resolve().parents[2]
MAGIC=0x1BADB002
# io.S exposes byte and dword port helpers only.  The ATA data register is
# 16 bits wide (two byte reads return the same low byte twice on QEMU), so the
# ATA driver needs a private inw/outw shim.  It is emitted as a build artifact
# instead of editing io.S, which belongs to other tasks.
ATA_IO_SHIM=r"""/* Generated by build_ferros.py: 16-bit port helpers for the ATA PIO driver.
 * System V AMD64: DI=port, SI=value; AX=u16 result.  Privileged instructions:
 * linked only into the freestanding kernel payload.
 */
.section .text,"ax",@progbits
.code64
.global ferros_ata_in16
.type ferros_ata_in16, @function
ferros_ata_in16:
    movl %edi, %edx
    xorl %eax, %eax
    inw %dx, %ax
    ret
.size ferros_ata_in16, .-ferros_ata_in16

.global ferros_ata_out16
.type ferros_ata_out16, @function
ferros_ata_out16:
    movl %edi, %edx
    movl %esi, %eax
    outw %ax, %dx
    ret
.size ferros_ata_out16, .-ferros_ata_out16
.section .note.GNU-stack,"",@progbits
"""


def inspect_image(path, elf_class):
    data=Path(path).read_bytes()
    if data[:6] != b"\x7fELF"+bytes([elf_class,1]):
        raise ValueError("unexpected ELF class or byte order")
    if struct.unpack_from("<HH",data,16)!=(2,62 if elf_class==2 else 3):
        raise ValueError("unexpected ELF type/machine")
    if elf_class==2:
        entry,phoff=struct.unpack_from("<QQ",data,24)
        phentsize,phnum=struct.unpack_from("<HH",data,54)
    else:
        entry,phoff=struct.unpack_from("<II",data,24)
        phentsize,phnum=struct.unpack_from("<HH",data,42)
    headers=[]
    for index in range(phnum):
        offset=phoff+index*phentsize
        if elf_class==2:
            kind,flags,fileoff,vaddr,paddr,filesz,memsz,align=struct.unpack_from("<IIQQQQQQ",data,offset)
        else:
            kind,fileoff,vaddr,paddr,filesz,memsz,flags,align=struct.unpack_from("<IIIIIIII",data,offset)
        if kind==1:
            if not (filesz<=memsz and fileoff+filesz<=len(data) and vaddr==paddr and paddr>=0x100000 and paddr+memsz<0x40000000):
                raise ValueError("LOAD segment outside bootstrap mapping or file")
            if flags&7==7: raise ValueError("unexpected RWX ELF LOAD segment")
            headers.append(dict(address=paddr,file_offset=fileoff,file_bytes=filesz,memory_bytes=memsz,flags=flags))
    if not any(h["address"]<=entry<h["address"]+h["memory_bytes"] and h["flags"]&1 for h in headers):
        raise ValueError("entry is outside executable LOAD segment")
    positions=[n for n in range(0,min(8192,len(data))-11,4) if struct.unpack_from("<I",data,n)[0]==MAGIC]
    if len(positions)!=1: raise ValueError("expected one aligned Multiboot header in first 8192 bytes")
    header,flags,checksum=struct.unpack_from("<III",data,positions[0])
    if flags!=3 or (header+flags+checksum)&0xffffffff: raise ValueError("invalid Multiboot flags/checksum")
    return dict(elf_class=elf_class,entry=hex(entry),multiboot_offset=positions[0],bytes=len(data),load_segments=headers)


def build_kernel(zen, output, release=False, main_override=None, unit_overrides=None, user_source_override=None, user_image_override=None):
    output=Path(output).resolve();output.mkdir(parents=True,exist_ok=True)
    log=[]
    def run(args):
        args=[str(a) for a in args]
        r=subprocess.run(args,capture_output=True,text=True,timeout=60)
        log.append("$ "+" ".join(args)+"\n"+r.stdout+r.stderr+f"exit={r.returncode}\n")
        if r.returncode: raise RuntimeError(log[-1])
        return r.stdout
    started=time.perf_counter()
    try:
        user=build_user(zen,output/"user",release,source_override=user_source_override)
        user_image=Path(user_image_override).resolve() if user_image_override else Path(user["artifact_path"])
        embedded=output/"user_image.S"
        embedded.write_text('.section .rodata.user_image,"a",@progbits\n.balign 8\n.Luser_image_start:\n.incbin '+json.dumps(str(user_image))+'\n.Luser_image_end:\n.section .text.user_image,"ax",@progbits\n.global ferros_user_image_start\nferros_user_image_start:\nleaq .Luser_image_start(%rip),%rax\nret\n.global ferros_user_image_end\nferros_user_image_end:\nleaq .Luser_image_end(%rip),%rax\nret\n.section .note.GNU-stack,"",@progbits\n')
        ata_io=output/"ata_io.S";ata_io.write_text(ATA_IO_SHIM)
        units=["arch/x86_64/abi.zen","drivers/serial.zen","memory.zen","drivers/ata.zen","interrupts.zen","scheduler.zen","vfs.zen","userspace.zen","runtime.zen","storage.zen","storage_fs.zen","main.zen"]
        combined=output/"kernel.zen"
        paths=[Path(main_override) if name=="main.zen" and main_override is not None else ROOT/"ferros/kernel"/name for name in units]
        if unit_overrides:
            paths=[Path(unit_overrides[name]) if name in unit_overrides else path for name,path in zip(units,paths)]
        combined.write_text("\n\n".join("// Source unit: "+str(path)+"\n"+path.read_text() for path in paths)+"\n")
        compiler=[Path(zen).resolve(),"build",combined,"--target","x86_64-unknown-none","--emit","obj","-o",output/"kernel.o"]
        if release: compiler.append("--release")
        run(compiler)
        cc=os.environ.get("CC","cc")
        for name,source in [("entry",ROOT/"ferros/boot/entry.S"),("io",ROOT/"ferros/kernel/arch/x86_64/io.S"),("ata_io",ata_io),("interrupts",ROOT/"ferros/kernel/arch/x86_64/interrupts.S"),("context",ROOT/"ferros/kernel/arch/x86_64/context.S"),("userspace",ROOT/"ferros/kernel/arch/x86_64/userspace.S"),("user_image",embedded)]:
            run([cc,"-c","-m64","-ffreestanding","-fno-pie",source,"-o",output/f"{name}.o"])
        payload=output/"ferros-x86_64.elf";image=output/"ferros-multiboot.elf"
        run(["ld","-m","elf_x86_64","-z","max-page-size=0x1000","-z","noexecstack","-nostdlib","-static","-T",ROOT/"ferros/boot/linker.ld",output/"entry.o",output/"kernel.o",output/"io.o",output/"ata_io.o",output/"interrupts.o",output/"context.o",output/"userspace.o",output/"user_image.o","-o",payload])
        run(["objcopy","-O","elf32-i386",payload,image])
        for artifact in [payload,image]:
            if run(["nm","-u",artifact]).strip(): raise ValueError("unresolved symbols in kernel")
        # Converting the loader container must leave the executable payload intact.
        for section in [".text",".rodata"]:
            for artifact,suffix in [(payload,"64"),(image,"32")]:
                run(["objcopy","--dump-section",f"{section}={output/(section[1:]+suffix+'.bin')}",artifact])
            if (output/(section[1:]+"64.bin")).read_bytes()!=(output/(section[1:]+"32.bin")).read_bytes():
                raise ValueError("loader conversion changed payload section")
        result=dict(source_units=units,source_paths=[str(p) for p in paths],release=release,user=user,user_image_path=str(user_image),payload=inspect_image(payload,2),image=inspect_image(image,1),build_seconds=round(time.perf_counter()-started,6),image_path=str(image),undefined_symbols=0)
        (output/"build.json").write_text(json.dumps(result,indent=2)+"\n")
        return result
    finally:
        (output/"build.log").write_text("\n".join(log))


def main():
    parser=argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--zen",type=Path,default=ROOT/"zen/compiler/target/release/zen")
    parser.add_argument("--output",type=Path)
    parser.add_argument("--release",action="store_true")
    args=parser.parse_args()
    output=args.output or ROOT/"ferros/build"/("release" if args.release else "debug")
    result=build_kernel(args.zen,output,args.release)
    print("Built",result["image_path"])

if __name__=="__main__":main()
